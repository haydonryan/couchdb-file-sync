#!/usr/bin/env bash
# Focused regression tests for scripts/update-dependencies.sh.
#
# Verifies, against mocked cargo/rustup/ssh and a sentinel HOME:
#   1. The updater's SSH identity/config are isolated in a temporary private
#      dir (never written to ~/.ssh) and cleaned up on both success/failure.
#   2. Pre-existing ~/.ssh files are never touched.
#   3. Lockfile-only upgrades (Cargo.toml untouched) are validated and committed.
#   4. A security-gate failure (cargo audit or cargo deny) prevents commit/push.
set -euo pipefail

SCRIPT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/scripts/update-dependencies.sh"
tmp="$(mktemp -d "${TMPDIR:-/tmp}/dep-updater-test.XXXXXX")"
trap 'rm -rf "$tmp"' EXIT

# --- sentinel HOME with pre-existing SSH files that must remain untouched ---
export HOME="$tmp/home"
mkdir -p "$HOME/.ssh"
printf 'PREEXISTING_KEY\n' > "$HOME/.ssh/id_ed25519"
printf 'PREEXISTING CONFIG\n' > "$HOME/.ssh/config"

# --- mocked toolchain in a PATH shim (first in PATH) ---
mockbin="$tmp/bin"
mkdir -p "$mockbin"

cat > "$mockbin/cargo" <<'MOCK'
#!/usr/bin/env bash
sub="$1"; shift
cmd="$(dirname "$0")/cargo-$sub"
if [[ -x "$cmd" ]]; then
  exec "$cmd" "$@"
fi
exit 0
MOCK

cat > "$mockbin/cargo-upgrade" <<'MOCK'
#!/usr/bin/env bash
exit 0
MOCK

cat > "$mockbin/cargo-update" <<'MOCK'
#!/usr/bin/env bash
# Record the isolated GIT_SSH_COMMAND so the temp config path is observable even
# in failure scenarios where no push (and therefore no real ssh call) happens.
if [[ -n "${MOCK_SSH_LOG:-}" ]]; then
  echo "ENV:${GIT_SSH_COMMAND:-unset}" >> "$MOCK_SSH_LOG"
fi
if [[ -n "${MOCK_FAIL_CHECK_AFTER_UPDATE:-}" ]]; then
  : > "${MOCK_FAIL_MARKER:?MOCK_FAIL_MARKER required}"
fi
if [[ "${MOCK_LOCKFILE_CHANGE:-1}" == "1" ]]; then
  printf '\n# mock lockfile bump\n' >> Cargo.lock
fi
exit 0
MOCK

for tool in test clippy fmt; do
  cat > "$mockbin/cargo-$tool" <<'MOCK'
#!/usr/bin/env bash
exit 0
MOCK
done

cat > "$mockbin/cargo-audit" <<'MOCK'
#!/usr/bin/env bash
if [[ "${MOCK_FAIL_CHECK_AFTER_UPDATE:-}" == "audit" && -f "${MOCK_FAIL_MARKER:-}" ]]; then
  exit 1
fi
exit 0
MOCK

cat > "$mockbin/cargo-deny" <<'MOCK'
#!/usr/bin/env bash
if [[ "${MOCK_FAIL_CHECK_AFTER_UPDATE:-}" == "deny" && -f "${MOCK_FAIL_MARKER:-}" ]]; then
  exit 1
fi
exit 0
MOCK

cat > "$mockbin/rustup" <<'MOCK'
#!/usr/bin/env bash
exit 0
MOCK

# Mock ssh: logs the full command line (which must carry the isolated -F config)
# and proxies git plumbing to the local bare remote so pushes really land.
cat > "$mockbin/ssh" <<'MOCK'
#!/usr/bin/env bash
if [[ -n "${MOCK_SSH_LOG:-}" ]]; then
  echo "$*" >> "$MOCK_SSH_LOG"
fi
for arg in "$@"; do
  if [[ "$arg" == git-receive-pack* || "$arg" == git-upload-pack* ]]; then
    exec bash -c "$arg"
  fi
done
exit 0
MOCK

chmod +x "$mockbin"/*
export PATH="$mockbin:$PATH"

# --- seed a real git repo + bare remote with one non-pinned dependency ---
git init -q --bare --initial-branch=main "$tmp/remote.git"
seed="$tmp/seed"
mkdir -p "$seed"
git -C "$seed" init -q
git -C "$seed" config user.name Seed
git -C "$seed" config user.email seed@example.com
printf 'seed\n' > "$seed/README"
git -C "$seed" add README
git -C "$seed" commit -qm seed
git -C "$seed" branch -m main
git -C "$seed" remote add origin "$tmp/remote.git"
git -C "$seed" push -q -u origin main

repo="$tmp/repo"
git clone -q "$tmp/remote.git" "$repo"
git -C "$repo" config core.hooksPath "$tmp/nohooks"
# Route pushes through an ssh:// transport so git invokes the mock ssh (which
# records the isolated -F config) and proxies git-receive-pack to the local bare.
git -C "$repo" remote set-url origin "ssh://git@localhost$tmp/remote.git"
mkdir -p "$tmp/nohooks"

cat > "$repo/Cargo.toml" <<'EOF'
[package]
name = "test-crate"
version = "0.1.0"
edition = "2021"

[dependencies]
serde = "1"
EOF

cat > "$repo/Cargo.lock" <<'EOF'
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "test-crate"
version = "0.1.0"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "1.0.210"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "0000000000000000000000000000000000000000"
EOF

git -C "$repo" add Cargo.toml Cargo.lock
git -C "$repo" -c user.name=Seed -c user.email=seed@example.com commit -qm baseline
git -C "$repo" push -q origin main

baseline="$(git -C "$repo" rev-parse HEAD)"
remote_baseline="$(git -C "$tmp/remote.git" rev-parse main)"
[[ "$baseline" == "$remote_baseline" ]]

fail_marker="$tmp/fail.flag"
ssh_log="$tmp/ssh.log"
: > "$ssh_log"

# Shared env for every scenario.
export GIT_BRANCH=main
export GIT_COMMIT_NAME="Dep Updater"
export GIT_COMMIT_EMAIL=dep@example.com
export GIT_PRIVATE_KEY="PRIVATE KEY MATERIAL"
export MOCK_FAIL_MARKER="$fail_marker"
export MOCK_SSH_LOG="$ssh_log"

run_reset() {
  git -C "$repo" fetch -q origin
  git -C "$repo" reset --hard -q origin/main
  git -C "$repo" clean -fdq
  rm -f "$fail_marker"
}

ssh_dir() {
  # Extract the -F <path> from the most recent ssh log line.
  grep -oE '\-F [^ ]+' "$ssh_log" | head -n1 | awk '{print $2}'
}

assert_no_credential_change() {
  [[ "$(cat "$HOME/.ssh/id_ed25519")" == "PREEXISTING_KEY" ]]
  [[ "$(cat "$HOME/.ssh/config")" == "PREEXISTING CONFIG" ]]
}

assert_ssh_isolated_and_cleaned() {
  local dir
  dir="$(ssh_dir)"
  [[ -n "$dir" ]]
  case "$dir" in
    "$tmp"/*/dep-updater-ssh.*) ;;
    /tmp/dep-updater-ssh.*) ;;
    *)
      echo "FAIL: ssh -F config not in an isolated temp dir: $dir" >&2
      exit 1
      ;;
  esac
  # Config must not point at the real HOME .ssh.
  [[ "$dir" != "$HOME/.ssh"* ]]
  # Temp SSH dir must have been cleaned up by the EXIT trap.
  [[ ! -e "$dir" ]]
  # No leftover temp ssh dirs anywhere.
  if compgen -G '/tmp/dep-updater-ssh.*' >/dev/null; then
    echo "FAIL: leftover /tmp/dep-updater-ssh.* dir" >&2
    exit 1
  fi
}

# ---------------------------------------------------------------------------
# Scenario 1: happy path — lockfile-only upgrade, all gates pass → committed+push
# ---------------------------------------------------------------------------
run_reset
pre_remote="$(git -C "$tmp/remote.git" rev-parse main)"
: > "$ssh_log"
set +e
( cd "$repo" && env MOCK_LOCKFILE_CHANGE=1 MOCK_FAIL_CHECK_AFTER_UPDATE="" "$SCRIPT" >"$tmp/s1.log" 2>&1 )
rc1=$?
set -e
[[ "$rc1" -eq 0 ]] || { echo "FAIL: happy path exit $rc1"; tail -40 "$tmp/s1.log"; exit 1; }

git -C "$repo" log --oneline -1 | grep -q 'Chore(deps): upgrade serde' \
  || { echo "FAIL: no upgrade commit on happy path"; tail -40 "$tmp/s1.log"; exit 1; }
git -C "$repo" diff --quiet "$pre_remote" -- Cargo.toml \
  || { echo "FAIL: Cargo.toml should be untouched (lockfile-only)"; exit 1; }
git -C "$repo" diff --quiet "$pre_remote" -- Cargo.lock \
  && { echo "FAIL: Cargo.lock should have changed"; exit 1; }
# Push landed on the remote (proves commit+push happened with isolated ssh).
remote_head="$(git -C "$tmp/remote.git" rev-parse main)"
[[ "$remote_head" != "$pre_remote" ]] || { echo "FAIL: no push to remote"; exit 1; }
assert_no_credential_change
assert_ssh_isolated_and_cleaned
echo "PASS: lockfile-only upgrade validated, committed and pushed; ssh isolated+cleaned"

# ---------------------------------------------------------------------------
# Scenario 2: cargo audit failure after update → no commit, no push, cleanup
# ---------------------------------------------------------------------------
run_reset
pre_remote="$(git -C "$tmp/remote.git" rev-parse main)"
: > "$ssh_log"
set +e
( cd "$repo" && env MOCK_LOCKFILE_CHANGE=1 MOCK_FAIL_CHECK_AFTER_UPDATE=audit "$SCRIPT" >"$tmp/s2.log" 2>&1 )
rc2=$?
set -e
[[ "$rc2" -ne 0 ]] || { echo "FAIL: audit-failure scenario should exit nonzero"; tail -40 "$tmp/s2.log"; exit 1; }

head_after="$(git -C "$repo" rev-parse HEAD)"
[[ "$head_after" == "$pre_remote" ]] || { echo "FAIL: audit failure produced a commit"; exit 1; }
remote_head="$(git -C "$tmp/remote.git" rev-parse main)"
[[ "$remote_head" == "$pre_remote" ]] || { echo "FAIL: audit failure pushed to remote"; exit 1; }
grep -q "audit" "$tmp/s2.log" || { echo "FAIL: audit failure not surfaced"; exit 1; }
assert_no_credential_change
assert_ssh_isolated_and_cleaned
echo "PASS: cargo audit failure prevented commit/push; ssh cleaned"

# ---------------------------------------------------------------------------
# Scenario 3: cargo deny failure after update → no commit, no push, cleanup
# ---------------------------------------------------------------------------
run_reset
pre_remote="$(git -C "$tmp/remote.git" rev-parse main)"
: > "$ssh_log"
set +e
( cd "$repo" && env MOCK_LOCKFILE_CHANGE=1 MOCK_FAIL_CHECK_AFTER_UPDATE=deny "$SCRIPT" >"$tmp/s3.log" 2>&1 )
rc3=$?
set -e
[[ "$rc3" -ne 0 ]] || { echo "FAIL: deny-failure scenario should exit nonzero"; tail -40 "$tmp/s3.log"; exit 1; }

head_after="$(git -C "$repo" rev-parse HEAD)"
[[ "$head_after" == "$pre_remote" ]] || { echo "FAIL: deny failure produced a commit"; exit 1; }
remote_head="$(git -C "$tmp/remote.git" rev-parse main)"
[[ "$remote_head" == "$pre_remote" ]] || { echo "FAIL: deny failure pushed to remote"; exit 1; }
grep -q "deny" "$tmp/s3.log" || { echo "FAIL: deny failure not surfaced"; exit 1; }
assert_no_credential_change
assert_ssh_isolated_and_cleaned
echo "PASS: cargo deny failure prevented commit/push; ssh cleaned"

echo "ALL update-dependencies.sh regression tests passed"
